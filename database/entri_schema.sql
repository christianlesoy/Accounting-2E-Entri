CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(32) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_users_username UNIQUE (username),
    CONSTRAINT uq_users_email UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS user_settings (
    user_id BIGINT NOT NULL,
    currency_code CHAR(3) NOT NULL DEFAULT 'USD',
    CONSTRAINT pk_user_settings PRIMARY KEY (user_id),
    CONSTRAINT chk_user_settings_currency CHECK (currency_code IN ('PHP','USD')),
    CONSTRAINT fk_user_settings_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS ledger_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    account_code VARCHAR(20) NOT NULL,
    account_name VARCHAR(100) NOT NULL,
    account_type VARCHAR(10) NOT NULL
        CHECK (account_type IN ('ASSET','LIABILITY','EQUITY','REVENUE','EXPENSE')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_ledger_user_code UNIQUE (user_id, account_code),
    CONSTRAINT uq_ledger_user_name UNIQUE (user_id, account_name),
    CONSTRAINT fk_ledger_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_ledger_user_type ON ledger_accounts(user_id, account_type);

CREATE TABLE IF NOT EXISTS journal_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    entry_date DATE NOT NULL,
    particulars VARCHAR(500) NOT NULL,
    currency CHAR(3) NOT NULL,
    entry_type VARCHAR(10) NOT NULL DEFAULT 'STANDARD'
        CHECK (entry_type IN ('STANDARD','ADJUSTMENT')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_journal_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_journal_user_date ON journal_entries(user_id, entry_date, id);

CREATE TABLE IF NOT EXISTS journal_entry_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journal_entry_id BIGINT NOT NULL,
    ledger_account_id BIGINT NOT NULL,
    account_name VARCHAR(100) NOT NULL,
    description VARCHAR(500) NOT NULL DEFAULT '',
    debit DECIMAL(19,4) NOT NULL DEFAULT 0.0000,
    credit DECIMAL(19,4) NOT NULL DEFAULT 0.0000,
    CONSTRAINT chk_journal_line_amounts CHECK (
        (debit > 0 AND credit = 0) OR (debit = 0 AND credit > 0)
    ),
    CONSTRAINT fk_journal_line_entry FOREIGN KEY (journal_entry_id)
        REFERENCES journal_entries(id) ON DELETE CASCADE,
    CONSTRAINT fk_journal_line_account FOREIGN KEY (ledger_account_id)
        REFERENCES ledger_accounts(id)
);
CREATE INDEX IF NOT EXISTS idx_journal_lines_entry ON journal_entry_lines(journal_entry_id);
CREATE INDEX IF NOT EXISTS idx_journal_lines_account ON journal_entry_lines(ledger_account_id);

CREATE TABLE IF NOT EXISTS recent_views (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    item_type VARCHAR(20) NOT NULL
        CHECK (item_type IN ('JOURNAL_ENTRY','LEDGER_ACCOUNT','WORKSHEET')),
    item_id BIGINT NULL,
    item_name VARCHAR(200) NOT NULL,
    viewed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_recent_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_recent_user_viewed ON recent_views(user_id, viewed_at);
